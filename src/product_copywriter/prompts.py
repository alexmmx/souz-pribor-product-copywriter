def build_input_message(product: ProductInput) -> str:
    """Serialize the product as the single factual context for the model."""

    source_json = json.dumps(
        product.model_dump(mode="json"),
        ensure_ascii=False,
        indent=2,
        sort_keys=True,
    )
    return (
        "Ниже входной JSON. Он является единственным источником фактов для карточки.\n\n"
        f"{source_json}"
    )

